/** Agrupa o catalogo por modulo, na ordem em que chega. */
export function agruparPorModulo(catalogo: PermissaoCatalogo[]): [string, PermissaoCatalogo[]][] {
  const grupos = new Map<string, PermissaoCatalogo[]>();
  for (const p of catalogo) {
    grupos.set(p.modulo, [...(grupos.get(p.modulo) ?? []), p]);
  }
  return [...grupos.entries()];
}
